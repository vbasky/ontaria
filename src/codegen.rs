//! Deterministic generators: JSON-LD context, source constants, JSON Schema,
//! SHACL skeletons, a property-graph schema, and Markdown docs.
//!
//! [`generate`] is the `build.rs` helper. The `terms!` proc macro lives in
//! `ontaria-macros` and is re-exported when the `codegen` feature is on.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use serde_json::{Map, Value, json};

use crate::error::{Error, Result};
use crate::model::{Ontology, Property, PropertyType};
use crate::parser::parse_document;
use crate::vocab::{self, local_name};

/// Write Rust constants for `path` into `out_dir/terms.rs`.
///
/// Call this from `build.rs`. The file is deterministic: terms are emitted
/// in IRI order, and a local-name collision gets a numeric suffix.
pub fn generate(path: impl AsRef<Path>, out_dir: impl AsRef<Path>) -> Result<()> {
    let path = path.as_ref();
    let bytes = fs::read(path).map_err(|source| Error::Read {
        path: path.to_path_buf(),
        source,
    })?;
    let base = path.to_string_lossy();
    let ontology = parse_document(&bytes, &base)?;
    let text = rust_source(&ontology);
    let destination = out_dir.as_ref().join("terms.rs");
    fs::write(&destination, text).map_err(|source| Error::Write {
        path: destination,
        source,
    })?;
    Ok(())
}

/// JSON-LD `@context` with prefixes and term definitions.
pub fn jsonld_context(ontology: &Ontology) -> Value {
    let mut context = Map::new();
    for (prefix, iri) in &ontology.namespaces {
        if prefix.is_empty() {
            continue;
        }
        context.insert(prefix.clone(), Value::String(iri.clone()));
    }
    for property in ontology.properties.values() {
        let name = ident_local(&property.uri);
        if name.is_empty() {
            continue;
        }
        let mut definition = Map::new();
        definition.insert("@id".to_string(), Value::String(property.uri.clone()));
        match property.kind {
            PropertyType::DatatypeProperty => {
                let datatype = property
                    .range
                    .iter()
                    .find(|iri| iri.starts_with(vocab::XSD))
                    .cloned()
                    .unwrap_or_else(|| format!("{}string", vocab::XSD));
                definition.insert("@type".to_string(), Value::String(datatype));
            }
            PropertyType::ObjectProperty => {
                definition.insert("@type".to_string(), Value::String("@id".to_string()));
            }
            PropertyType::AnnotationProperty => {}
        }
        if wants_set(property) {
            definition.insert("@container".to_string(), Value::String("@set".to_string()));
        }
        context.insert(name, Value::Object(definition));
    }
    json!({ "@context": context })
}

/// Rust source with `classes::` constants and a `Class` enum.
pub fn rust_source(ontology: &Ontology) -> String {
    let classes = names(ontology.classes.keys().map(String::as_str));
    let properties = names(ontology.properties.keys().map(String::as_str));
    let mut out = String::from("// Generated by ontaria. Do not edit.\n");
    out.push_str("#[allow(dead_code)]\npub mod classes {\n");
    for (iri, name) in &classes {
        out.push_str(&format!("    pub const {name}: &str = \"{iri}\";\n"));
    }
    out.push_str("}\n\n#[allow(dead_code)]\npub mod properties {\n");
    for (iri, name) in &properties {
        out.push_str(&format!("    pub const {name}: &str = \"{iri}\";\n"));
    }
    out.push_str("}\n\n");
    if !classes.is_empty() {
        out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub enum Class {\n");
        for (_, name) in &classes {
            out.push_str(&format!("    {},\n", pascal(name)));
        }
        out.push_str(
            "}\n\nimpl Class {\n    pub fn iri(self) -> &'static str {\n        match self {\n",
        );
        for (_, name) in &classes {
            out.push_str(&format!(
                "            Self::{} => classes::{name},\n",
                pascal(name)
            ));
        }
        out.push_str("        }\n    }\n}\n");
    }
    out
}

fn wants_set(property: &Property) -> bool {
    if property.functional {
        return false;
    }
    true
}

fn ident_local(iri: &str) -> String {
    local_name(iri).to_string()
}

fn names<'a>(iris: impl Iterator<Item = &'a str>) -> Vec<(String, String)> {
    let mut items: Vec<String> = iris.map(str::to_string).collect();
    items.sort();
    items.dedup();
    let mut used = BTreeMap::<String, usize>::new();
    let mut named = Vec::new();
    for iri in items {
        let base = shouty(&ident_local(&iri));
        let count = used.entry(base.clone()).or_insert(0);
        *count += 1;
        let name = if *count == 1 {
            base
        } else {
            format!("{base}_{count}")
        };
        named.push((iri, name));
    }
    named
}

fn shouty(local: &str) -> String {
    let mut out = String::new();
    let mut prev_lower = false;
    for ch in local.chars() {
        if ch.is_ascii_uppercase() && prev_lower {
            out.push('_');
        }
        if ch.is_ascii_alphanumeric() {
            out.push(ch.to_ascii_uppercase());
            prev_lower = ch.is_ascii_lowercase();
        } else if !out.ends_with('_') && !out.is_empty() {
            out.push('_');
            prev_lower = false;
        }
    }
    let out = out.trim_matches('_').to_string();
    let out = if out.is_empty() {
        "TERM".to_string()
    } else {
        out
    };
    let mut out = if out.chars().next().is_some_and(|ch| ch.is_ascii_digit()) {
        format!("N_{out}")
    } else {
        out
    };
    if is_keyword(&out.to_ascii_lowercase()) {
        out = format!("R#{out}");
    }
    out
}

fn pascal(shouty_name: &str) -> String {
    let raw = shouty_name.trim_start_matches("R#");
    let mut out = String::new();
    let mut upper = true;
    for ch in raw.chars() {
        if ch == '_' {
            upper = true;
            continue;
        }
        if upper {
            out.push(ch.to_ascii_uppercase());
            upper = false;
        } else {
            out.push(ch.to_ascii_lowercase());
        }
    }
    if out.chars().next().is_some_and(|ch| ch.is_ascii_digit()) {
        out = format!("N{out}");
    }
    out
}

fn is_keyword(word: &str) -> bool {
    matches!(
        word,
        "as" | "async"
            | "await"
            | "break"
            | "const"
            | "continue"
            | "crate"
            | "else"
            | "enum"
            | "extern"
            | "false"
            | "fn"
            | "for"
            | "if"
            | "impl"
            | "in"
            | "let"
            | "loop"
            | "match"
            | "mod"
            | "move"
            | "mut"
            | "pub"
            | "ref"
            | "return"
            | "self"
            | "static"
            | "struct"
            | "super"
            | "trait"
            | "true"
            | "type"
            | "unsafe"
            | "use"
            | "where"
            | "while"
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parser::parse_document;

    fn ontology() -> Ontology {
        parse_document(
            br#"
            @prefix ex: <http://example.org/> .
            @prefix owl: <http://www.w3.org/2002/07/owl#> .
            @prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
            @prefix xsd: <http://www.w3.org/2001/XMLSchema#> .
            ex: a owl:Ontology .
            ex:Person a owl:Class ; rdfs:label "Person" ; rdfs:comment "A person" ;
              rdfs:subClassOf [ a owl:Restriction ; owl:onProperty ex:name ; owl:minCardinality 1 ] .
            ex:name a owl:DatatypeProperty ; rdfs:label "name" ; rdfs:range xsd:string .
            ex:knows a owl:ObjectProperty ; rdfs:label "knows" ; rdfs:range ex:Person .
            "#,
            "http://example.org/",
        )
        .unwrap()
    }

    #[test]
    fn generators_are_stable_and_name_the_person_class() {
        let ontology = ontology();
        let rust = rust_source(&ontology);
        assert_eq!(rust, rust_source(&ontology));
        assert!(rust.contains("pub const PERSON: &str = \"http://example.org/Person\";"));
        assert!(rust.contains("enum Class"));
        let context = jsonld_context(&ontology);
        assert!(
            context["@context"]["name"]["@type"]
                .as_str()
                .unwrap()
                .ends_with("string")
        );
        assert_eq!(context["@context"]["knows"]["@container"], "@set");
    }
}
